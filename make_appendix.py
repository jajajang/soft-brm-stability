"""Writes appendix_E.tex with every number taken from summary.json and constants_*.json."""

import json

import numpy as np

S = json.load(open("summary.json"))
C = json.load(open("constants_H16_n800.json"))
iid, traj = S["iid"], S["trajectory"]
cols = [("iid", "8"), ("iid", "16"), ("iid", "32"), ("trajectory", "16")]
ns = iid["16"]["n"]


def entry(kind, H):
    return (iid if kind == "iid" else traj)[H]


def cell(kind, H, key, i, dec):
    e = entry(kind, H)
    n = e["n"][i]
    return f"${n * e[key + '_mean'][i]:.{dec}f}$ {{\\scriptsize$\\pm{n * e[key + '_se'][i]:.{dec}f}$}}"


def slope(kind, H, key):
    s, lo, hi = entry(kind, H)[key + "_slope"]
    return f"${s:.2f}$", f"{{\\scriptsize$[{lo:.2f},{hi:.2f}]$}}"


def table(key, dec, oracle=False):
    lines = ["\\begin{tabular}{@{}r" + "c" * (len(cols) + int(oracle)) + "@{}}", "\\toprule"]
    head = " & \\multicolumn{3}{c}{i.i.d.\\ data} & single trajectory"
    sub = "$n$ & $H=8$ & $H=16$ & $H=32$ & $H=16$"
    if oracle:
        head += " & exact empirical"
        sub += " & minimizer (i.i.d.)"
    lines += [head + " \\\\", "\\cmidrule(lr){2-4}", sub + " \\\\", "\\midrule"]
    for i, n in enumerate(ns):
        row = [cell(k, H, key, i, dec) for k, H in cols]
        if oracle:
            row.append(f"${n * iid['16']['oracle_mean'][i]:.{dec}f}$")
        lines.append(f"{n} & " + " & ".join(row) + " \\\\")
    lines.append("\\midrule")
    pairs = [slope(k, H, key) for k, H in cols]
    if oracle:
        s_, lo, hi = iid["16"]["oracle_slope"]
        pairs.append((f"${s_:.2f}$", f"{{\\scriptsize$[{lo:.2f},{hi:.2f}]$}}"))
    lines.append("slope ($n\\ge 200$) & " + " & ".join(p_[0] for p_ in pairs) + " \\\\")
    lines.append("95\\% interval & " + " & ".join(p_[1] for p_ in pairs) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def rng_of(key, kind="iid", Hs=("8", "16", "32"), n_min=200):
    vals = []
    for H in Hs:
        e = entry(kind, H)
        vals += [n * m for n, m in zip(e["n"], e[key + "_mean"]) if n >= n_min]
    return min(vals), max(vals)


def slopes_range(key, kind="iid", Hs=("8", "16", "32")):
    s = [entry(kind, H)[key + "_slope"][0] for H in Hs]
    return min(s), max(s)


# optimization diagnostics
tr = [r for H in ("8", "16", "32") for r in iid[H]["eps_w_T_ratio"]] + traj["16"]["eps_w_T_ratio"]
ratio = [m / o for H in ("8", "16", "32") for m, o in zip(iid[H]["msbe_mean"], iid[H]["oracle_mean"])]
ratio_by_n = {n: [iid[H]["msbe_mean"][i] / iid[H]["oracle_mean"][i] for H in ("8", "16", "32")]
              for i, n in enumerate(ns)}
max_small = max(max(v) for n, v in ratio_by_n.items() if 200 <= n <= 3200)
max_6400 = max(ratio_by_n[6400])
gg = rng_of("gen_gap", Hs=("8", "16", "32"))

# constants
rows = C["rows"]


def consts(tmin, agg):
    get = lambda k: np.array([r[k] for r in rows if r["t"] >= tmin])
    if agg == "worst":
        mu, rho, qg, G, L = get("mu_pl").min(), get("rho").min(), get("mu_qg").min(), get("G").max(), get("L").max()
    else:
        mu, rho, qg, G, L = (np.median(get(k)) for k in ("mu_pl", "rho", "mu_qg", "G", "L"))
    Lphi = L * (1 + L / rho)
    Sw = 2 * G * (1 + L / rho) / np.sqrt(mu * qg)
    stat = Lphi * (1 + L / rho) ** 2 * G ** 2 / (mu * qg)
    return dict(mu=mu, rho=rho, qg=qg, G=G, L=L, Sw=Sw, stat=stat)


W = consts(0, "worst")
Lt = consts(5000, "median")
e16 = iid["16"]
neps16 = np.mean([n * m for n, m in zip(e16["n"], e16["eps_w_mean"]) if n >= 200])
nmsbe16 = np.mean([n * m for n, m in zip(e16["n"], e16["msbe_mean"]) if n >= 200])


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"{m}\\times10^{{{int(e)}}}"


